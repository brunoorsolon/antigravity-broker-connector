import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn, spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';

test('disposable proof generator is no-overwrite, hook is metadata-only, waiter is one-shot', async t => {
  const root = mkdtempSync(join(tmpdir(),'agy-proof-test-'));
  t.after(() => rmSync(root,{recursive:true,force:true}));
  const target=join(root,'plugin'), generator=fileURLToPath(new URL('../scripts/prepare-native-proof.mjs',import.meta.url));
  const generated=spawnSync(process.execPath,[generator,target],{encoding:'utf8'});
  assert.equal(generated.status,0,generated.stderr);
  assert.equal(JSON.parse(generated.stdout).installed,false);
  assert.notEqual(spawnSync(process.execPath,[generator,target]).status,0);
  assert.deepEqual(Object.keys(JSON.parse(readFileSync(join(target,'plugin.json'),'utf8'))).sort(),['description','name']);
  const runner=join(target,'proof.mjs');
  const hook=spawnSync(process.execPath,[runner,'hook'],{input:JSON.stringify({conversationId:randomUUID(),modelName:'secret-payload'}),encoding:'utf8'});
  assert.equal(hook.status,0); assert.equal(hook.stdout.includes('secret-payload'),false);
  assert.notEqual(spawnSync(process.execPath,[runner,'hook'],{input:'{"conversationId":"../../bad"}'}).status,0);
  const child=spawn(process.execPath,[runner,'wait'],{stdio:['ignore','pipe','pipe']});
  let out='';child.stdout.on('data',chunk=>{out+=chunk;});
  const exit=new Promise(resolve=>child.on('exit',resolve));
  const timer=setTimeout(()=>child.kill(),3000); t.after(()=>clearTimeout(timer));
  assert.equal(spawnSync(process.execPath,[runner,'signal']).status,0);
  assert.equal(await exit,0);
  assert.match(out,/PSST_NATIVE_WAKE_PROOF/);
  assert.equal(out.split('\n').filter(Boolean).length,1);
});
